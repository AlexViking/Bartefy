// Writes src/components/ui/material-paths.ts: the Material Symbols (Outlined,
// weight 400, 24px grid) the app draws, from Google's release SVGs (Apache
// License 2.0). One place to add an icon: put its name in OUTLINE, and in
// FILLED too if the design draws it filled; then run this script.
//   node scripts/gen-material-icons.mjs
import fs from 'node:fs'

const OUTLINE = `
add add_a_photo add_circle add_photo_alternate alarm apparel arrow_back arrow_forward
auto_awesome autorenew bar_chart bolt chair chat chat_bubble check check_circle chevron_left
chevron_right child_care circle close cooking dark_mode delete devices diamond drafts edit
expand_less expand_more explore extension favorite flag group_add handshake handyman info
inventory_2 language layers left_panel_close left_panel_open light_mode local_fire_department
location_on lock logout mail menu menu_book mic more_vert museum music_note near_me
notifications open_in_full palette pause pedal_bike person photo_camera play_arrow
remove remove_moderator schedule search settings shield shield_person star style sync_alt
table_restaurant toll translate trending_up undo verified verified_user weekend yard
`.split(/\s+/).filter(Boolean)

/** Drawn filled somewhere in the V6 mocks (font-variation-settings 'FILL' 1). */
const FILLED = `
alarm bolt check_circle circle favorite local_fire_department location_on shield star style
table_restaurant verified
`.split(/\s+/).filter(Boolean)

const base = 'https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsoutlined'
async function path(name, variant) {
  const r = await fetch(`${base}/${name}/${variant}/24px.svg`)
  if (!r.ok) throw new Error(`${name} ${variant}: HTTP ${r.status}`)
  const svg = await r.text()
  const ds = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1])
  if (!ds.length) throw new Error(`${name} ${variant}: no path`)
  return ds.join(' ')
}

const rows = []
for (const n of OUTLINE) rows.push([n, await path(n, 'default')])
for (const n of FILLED) rows.push([n + '_fill', await path(n, 'fill1')])
rows.sort((a, b) => a[0].localeCompare(b[0]))

const out = `// GENERATED by scripts/gen-material-icons.mjs -- do not edit by hand.
// Material Symbols Outlined, weight 400, viewBox "0 -960 960 960".
// Apache License 2.0, Google.
export const MATERIAL_PATHS = {
${rows.map(([n, d]) => `  ${n}: '${d}',`).join('\n')}
} as const

export type MaterialIconName = keyof typeof MATERIAL_PATHS
`
fs.writeFileSync('src/components/ui/material-paths.ts', out)
console.log(`${rows.length} icons written`)
